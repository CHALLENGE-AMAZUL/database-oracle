DROP TABLE tb_artigo;
DROP TABLE tb_fonte;
DROP TABLE tb_artigo_fonte;
DROP TABLE tb_local;

--Criar os SEQUENCES

CREATE TABLE tb_local (
    id          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR2(150) NOT NULL,
    pais   VARCHAR2(100),
    codigo_pais CHAR(2),
    latitude    VARCHAR2(30),
    longitude   VARCHAR2(30)
);

CREATE TABLE tb_fonte (
    id            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo        VARCHAR2(150) NOT NULL,
    url           VARCHAR2(500) NOT NULL UNIQUE,
    data_consulta DATE DEFAULT SYSDATE,
    atualizado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE tb_artigo (
    id                NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_aplicacao    VARCHAR2(30)  NOT NULL CHECK (area_aplicacao IN ('ENERGIA', 'SAUDE', 'AGRICULTURA', 'INDUSTRIA', 'PESQUISA')),
    titulo            VARCHAR2(150) NOT NULL,
    resumo            VARCHAR2(500) NOT NULL,
    aplicacao_real    VARCHAR2(1500) NOT NULL,
    impacto_sociedade VARCHAR2(1500) NOT NULL,
    status_artigo            VARCHAR2(20)  DEFAULT 'RASCUNHO' NOT NULL CHECK (status IN ('RASCUNHO', 'PUBLICADO', 'ARQUIVADO')),
    atualizado_em     TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    id_local          NUMBER(19),
    CONSTRAINT fk_artigo_local FOREIGN KEY (id_local) REFERENCES local(id)
);

CREATE TABLE artigo_fonte (
    id         NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artigo_id  NUMBER(19) NOT NULL,
    fonte_id   NUMBER(19) NOT NULL,
    observacao VARCHAR2(255),
    CONSTRAINT fk_af_artigo FOREIGN KEY (artigo_id) REFERENCES artigo(id) ON DELETE CASCADE,
    CONSTRAINT fk_af_fonte  FOREIGN KEY (fonte_id)  REFERENCES fonte(id)  ON DELETE CASCADE,
    CONSTRAINT uk_artigo_fonte UNIQUE (artigo_id, fonte_id)
);